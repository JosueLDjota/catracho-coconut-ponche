let currentLang = localStorage.getItem("catracho_store_lang") || "en";
if (!translations[currentLang]) currentLang = "en";

/**
 * Traduce una clave. Permite variables con formato {nombre}.
 */
function t(key, vars = {}) {
  const dict = translations[currentLang] || translations.en;
  let text = dict[key];
  if (text === undefined) text = translations.en[key] || translations.es[key];
  if (text === undefined) return key;
  return String(text).replace(/\{(\w+)\}/g, (match, name) => {
    return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match;
  });
}

function getI18n(key, vars) {
  return t(key, vars);
}

function applyTranslations() {
  const lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.setAttribute("title", t(key));
  });

  const langBtnText = document.getElementById("langBtnLabel");
  if (langBtnText) langBtnText.textContent = lang === "es" ? "EN" : "ES";

  const langBtn = document.getElementById("langToggle");
  if (langBtn) {
    langBtn.setAttribute("aria-label", t("nav.lang"));
    langBtn.setAttribute("title", t("nav.lang"));
  }

  document.documentElement.lang = lang;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  try {
    localStorage.setItem("catracho_store_lang", lang);
  } catch (error) {
    /* El almacenamiento puede estar bloqueado; la interfaz sigue funcionando. */
  }

  applyTranslations();
  window.dispatchEvent(new CustomEvent("storeLangChange", { detail: { lang } }));
}

function toggleLanguage() {
  setLanguage(currentLang === "es" ? "en" : "es");
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
});
